it('Synth matches the original unbounded mulberry32 for 100,000 consecutive outputs', () => {
    const seed = 0xffffffff;
    const next = shared().mulberry32(seed);
    let state = seed >>> 0;
    const legacy = () => {
        let t = (state += 0x6d2b79f5);
        t = Math.imul(t ^ (t >>> 15), t | 1);
        t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
    for (let i = 0; i < 100_000; i++) {
        expect(next(), 'Synth sequence index ' + i).toBe(legacy());
    }
});
