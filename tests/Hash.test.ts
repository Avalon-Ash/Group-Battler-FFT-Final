function shared(): Record<string, Function> {
    const file = 'engine/math/hash.ts';
    if (!fs.existsSync(file)) return {};
    const exports = {};
    new Function('exports', ts.transpile(fs.readFileSync(file, 'utf8'), { module: ts.ModuleKind.CommonJS }))(exports);
    return exports;
}
function load(file: string, name: string, replacement?: string): Function {
    const text = fs.readFileSync(file, 'utf8');
    const tree = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
    let expression = '';
    function visit(node: ts.Node): void {
        if (ts.isFunctionDeclaration(node) && node.name?.text === name) expression = node.getText(tree).replace(/^export /, '');
        if (ts.isVariableDeclaration(node) && node.name.getText(tree) === name && node.initializer && ts.isArrowFunction(node.initializer)) expression = node.initializer.getText(tree);
        ts.forEachChild(node, visit);
    }
    visit(tree);
    const deps = shared();
    if (!expression) {
        const fn = deps[replacement ?? name];
        if (!fn) throw new Error('Missing implementation: ' + file + ':' + name);
        return fn;
    }
    const js = ts.transpile('const target = ' + expression + ';', { target: ts.ScriptTarget.ES2022 });
    return new Function(...Object.keys(deps), js + '\nreturn target;')(...Object.values(deps));
}
function originalFNV(str: string): number {
    if (fs.existsSync('engine/math/hash.ts')) return shared().fnv1a32(str);
    const src = fs.readFileSync('data/units/appearance/bodyTypes.ts', 'utf8');
    const block = src.slice(src.indexOf('    let hash ='), src.indexOf('    const norm ='));
    return new Function('seedStr', block + 'return u32;')(str);
}
function audio(seed: number): () => number {
    const src = fs.readFileSync('engine/audio/Synth.ts', 'utf8');
    const tree = ts.createSourceFile('Synth.ts', src, ts.ScriptTarget.Latest, true);
    let body = '';
    function visit(n: ts.Node): void {
        if (ts.isMethodDeclaration(n) && n.name.getText(tree) === 'next') body = n.body!.getText(tree);
        ts.forEachChild(n, visit);
    }
    visit(tree);
    if (body.includes('this.state')) return new Function(body.slice(1, -1)).bind({state: seed >>> 0});
    return shared().mulberry32(seed);
}
